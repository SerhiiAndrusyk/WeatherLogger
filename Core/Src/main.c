/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_SPI1_Init();
  MX_RTC_Init();
  /* USER CODE BEGIN 2 */
  DISPLAY_Init();
  MemoryInit();
  SensorInit();
  displayLastActivity = HAL_GetTick();
  DISPLAY_WriteStart();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	if (sleepMode){
		displayActive = false;
		sleepMode = false;
		DISPLAY_Off();
		HAL_SuspendTick();
		HAL_PWREx_EnterSTOP2Mode(PWR_STOPENTRY_WFI);
		HAL_ResumeTick();
		SystemClock_Config();
	}
	if (displayWakeRequested && !displayActive){
		displayActive = true;
		DISPLAY_On();
	}
	if ((mode%4 == 0 && displayActive) && (mode != prevmode)){
		prevmode = mode;
		DISPLAY_WriteStart();
	}
	else if ((displayActive && mode%4 != 0) &&
			((mode != prevmode) || (page != prevpage))){
		prevmode = mode;
		prevpage = page;
		DISPLAY_WritePage(mode%4, page);
	}
	if (nextButtonPressed){
		nextButtonPressed = false;
		page++;
	}
	if (backButtonPressed){
		backButtonPressed = false;
		if (page > 0U){
			page--;
		}
	}
	if (nextButtonDoublePressed){
		nextButtonDoublePressed = false;
		if (mode%4 == 1){
			page /= 24;
		}
		else if (mode%4 == 2){
			page /= 30;
		}
		else if (mode%4 == 3){
			page *= 720;
		}
		mode++;
	}
	if (backButtonDoublePressed){
		backButtonDoublePressed = false;
		if (mode%4 == 0){
			sleepMode = true;
			displayWakeRequested = false;
			page = 0;
		}
		else{
			if (mode%4 == 3){
				page *= 30;
			}
			else if (mode%4 == 2){
				page *= 24;
			}
			mode--;
		}
	}
	if (measurementRequired){
		measurementRequired = false;
		Logger_Process();
		if (!displayActive){
			sleepMode = true;
		}
	}
	if (displayActive && (HAL_GetTick() - displayLastActivity >= DISPLAY_TIMEOUT_MS)){
		displayActive = false;
		sleepMode = true;
		displayWakeRequested = false;
		DISPLAY_Off();
	}
  }
  /* USER CODE END 3 */
}

